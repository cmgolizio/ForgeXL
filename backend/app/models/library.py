"""The persistent Data Library's domain model (build plan Phase 9A, 9B).

The Data Library is where ForgeXL keeps *business data* — sales history, sample
history and account-assignment snapshots — as opposed to the ephemeral *runtime
state* of a Run, which lives in :mod:`app.services.run_store`. The build plan
states the separation as a rule of its own:

    RunStore     -> temporary execution/runtime state
    Data Library -> persistent business datasets used across Runs

This module models what the library holds. It does not decide where any of it
is written: that belongs to :mod:`app.services.data_library`, so no business
logic ever names a filesystem location (build plan 9A).

Three kinds of value live here:

* :class:`DatasetDefinition` — a logical dataset ForgeXL knows about, declared
  in code. The three the build plan requires are declared at the bottom of this
  module.
* :class:`Dataset` and :class:`DatasetVersion` — the records the library
  persists. Pydantic, because they are written to disk as JSON and validated
  again when they are read back; a record that no longer validates is a
  corrupt record, and saying so is the point.
* :class:`DatasetCommit` — the request to commit one version. A plain frozen
  dataclass, because it carries a Polars DataFrame, which is never serialised
  and which Pydantic could not validate anyway. The same reasoning that keeps
  :class:`~app.actions.base.ActionResult` and
  :class:`~app.models.run.RunResult` out of Pydantic.

Identity rules, both of which exist so a client-supplied value can never become
a filesystem path:

* A dataset ID is a lowercase identifier declared by ForgeXL code
  (:func:`parse_dataset_id`).
* A dataset version ID is generated by ForgeXL as a UUID and validated as one
  (:func:`new_version_id`, :func:`parse_version_id`) — the same convention Run
  IDs follow, and the reason build plan 9B insists version IDs are not derived
  from user filenames.
"""

from __future__ import annotations

import hashlib
import re
import uuid
from collections.abc import Iterator
from contextlib import contextmanager
from dataclasses import dataclass
from datetime import date, datetime, timezone
from enum import Enum

import polars as pl
from pydantic import BaseModel, ConfigDict, Field, model_validator

from app.errors import (
    InvalidDatasetCommitError,
    UnknownDatasetError,
    UnknownDatasetVersionError,
    WorkbenchError,
)
from app.models.schemas import ColumnSchema

#: Version of the persisted Data Library record format. Bump when the shape of
#: ``dataset.json`` or ``version.json`` changes incompatibly, so a record
#: written by an older build stays identifiable rather than being misread.
#:
#: Mirrors :data:`app.models.schemas.MANIFEST_SCHEMA_VERSION`, and exists for
#: the same reason: persisted state outlives the code that wrote it.
LIBRARY_SCHEMA_VERSION = 1


# ---------------------------------------------------------------------------
# Identity
# ---------------------------------------------------------------------------

#: A dataset ID is a lowercase snake_case identifier. It is declared by
#: ForgeXL code, never by a user, and it is the one value that becomes a
#: directory name — so it is checked against this before it is used as one.
DATASET_ID_PATTERN = re.compile(r"^[a-z][a-z0-9_]*$")

#: A reporting period is a calendar month, canonically ``YYYY-MM``. Months
#: sort correctly as text in this form, which is why it is the stored form.
PERIOD_PATTERN = re.compile(r"^(\d{4})-(0[1-9]|1[0-2])$")


def parse_dataset_id(raw: str) -> str:
    """Validate a dataset ID, returning it unchanged.

    Anything that is not a plain lowercase identifier — a path fragment, an
    absolute path, a name with separators or spaces — raises
    :class:`~app.errors.UnknownDatasetError` rather than reaching a filesystem.
    An unknown-but-well-formed ID is reported by the library itself; this is
    only about the shape.
    """
    if not isinstance(raw, str) or not DATASET_ID_PATTERN.fullmatch(raw):
        raise UnknownDatasetError(
            "That is not a valid dataset ID.", details={"dataset_id": raw}
        )
    return raw


def new_version_id() -> str:
    """Generate the ID of one committed dataset version (build plan 9B).

    ForgeXL generates it. It is never derived from the uploaded filename, which
    is untrusted text and is recorded as metadata only.
    """
    return str(uuid.uuid4())


def parse_version_id(raw: str) -> str:
    """Validate a dataset version ID, returning its canonical form.

    Accepts only the canonical string form of a UUID, exactly as
    :func:`app.models.run.parse_run_id` does for Run IDs. A truncated,
    traversal-shaped or invented ID is refused here rather than being used to
    build a path.
    """
    try:
        parsed = uuid.UUID(raw)
    except (ValueError, AttributeError, TypeError):
        raise UnknownDatasetVersionError(
            "That is not a valid dataset version ID.", details={"version_id": raw}
        ) from None
    if str(parsed) != raw.lower():
        raise UnknownDatasetVersionError(
            "That is not a valid dataset version ID.", details={"version_id": raw}
        )
    return str(parsed)


def parse_period(raw: str) -> str:
    """Validate a reporting period, returning its canonical ``YYYY-MM`` form.

    A period is a calendar month. It is validated rather than accepted as free
    text because it is an identity in this system: "the September 2026 sales
    version" and "the September 2026 ownership snapshot" have to name the same
    month in the same way for a report to be reproducible (build plan 9E).

    Raises:
        InvalidDatasetCommitError: the value is not a ``YYYY-MM`` month.
    """
    if not isinstance(raw, str) or not PERIOD_PATTERN.fullmatch(raw):
        raise InvalidDatasetCommitError(
            "A reporting period must be a calendar month written as YYYY-MM, "
            f"for example 2026-09. Received {raw!r}.",
            details={"period": raw},
        )
    return raw


def content_hash(payload: bytes) -> str:
    """Return the SHA-256 hex digest of an uploaded source file.

    Defined in one place so every caller hashes the same way. Build plan 10C
    detects an already-imported identical file by comparing this digest, which
    only works if there is exactly one definition of it.
    """
    return hashlib.sha256(payload).hexdigest()


def now() -> datetime:
    """The timestamp a Data Library record carries, always UTC."""
    return datetime.now(timezone.utc)


@contextmanager
def _as_validation_failure() -> Iterator[None]:
    """Re-raise an identity refusal as the ``ValueError`` Pydantic understands.

    The :func:`parse_dataset_id` / :func:`parse_version_id` / :func:`parse_period`
    rules are defined once and used in two places: at the boundary, where a bad
    ID is a 404 or a 422 with a code the UI can act on, and inside the model
    validators below, where a bad ID means *this stored record is not valid*.

    Pydantic converts only ``ValueError`` and ``AssertionError`` into a
    :class:`~pydantic.ValidationError`; anything else escapes as itself. That
    difference matters: a corrupt ``version.json`` must surface as an invalid
    record — which the Data Library reports as corrupt persistent state — and
    not as ``UnknownDatasetVersionError``, which means the perfectly healthy
    "no such version". This adapter keeps one definition of each rule while
    letting each context report the failure it actually has.
    """
    try:
        yield
    except WorkbenchError as error:
        raise ValueError(error.message) from error


