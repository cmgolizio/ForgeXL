class DatasetKind(str, Enum):
    """What a dataset's versions mean together (build plan 9B "dataset type").

    The distinction is semantic rather than structural — both kinds are stored
    the same way — and it is the distinction build plan 9E turns on:

    * :attr:`HISTORY` accumulates. Each version adds a reporting period, and a
      report reads many of them together. Sales and sample history are this.
    * :attr:`SNAPSHOT` does not accumulate. Each version states the whole truth
      as of one reporting period, and a report reads exactly the period it is
      reporting on. Account assignments are this: an account owned by one rep
      in September and another in November must regenerate September's report
      against September's ownership, not today's.
    """

    HISTORY = "history"
    SNAPSHOT = "snapshot"


class DatasetDefinition(BaseModel):
    """A logical dataset ForgeXL knows about, declared in code.

    Declared rather than discovered, for the same reason Actions are: the
    library is application code, not a plugin loader. The definitions the build
    plan requires are :data:`KNOWN_DATASETS` at the bottom of this module.
    """

    model_config = ConfigDict(frozen=True)

    id: str = Field(description="Stable logical dataset ID, e.g. 'sales_history'.")
    kind: DatasetKind
    label: str = Field(description="Human-readable dataset name.")
    description: str

    @model_validator(mode="after")
    def _check_id(self) -> DatasetDefinition:
        with _as_validation_failure():
            parse_dataset_id(self.id)
        return self


class Dataset(BaseModel):
    """A dataset as the library has recorded it (``dataset.json``).

    Created from a :class:`DatasetDefinition` the first time the dataset is
    used. It carries `created_at` because a definition is code and this is a
    record: when the dataset first existed in *this* library is a fact only the
    library knows.
    """

    model_config = ConfigDict(frozen=True)

    schema_version: int = LIBRARY_SCHEMA_VERSION
    id: str
    kind: DatasetKind
    label: str
    description: str
    created_at: datetime

    @classmethod
    def of(
        cls, definition: DatasetDefinition, *, created_at: datetime | None = None
    ) -> Dataset:
        """Build the record for `definition`, stamped now unless told otherwise."""
        return cls(
            id=definition.id,
            kind=definition.kind,
            label=definition.label,
            description=definition.description,
            created_at=created_at or now(),
        )

    def definition(self) -> DatasetDefinition:
        """Return the declaration this record was created from."""
        return DatasetDefinition(
            id=self.id,
            kind=self.kind,
            label=self.label,
            description=self.description,
        )


