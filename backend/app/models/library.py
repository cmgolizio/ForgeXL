class DatasetVersion(BaseModel):
    """One immutable committed version of one dataset (``version.json``).

    Build plan 9B lists what a version must record. Each item, and where it is:

    ==============================  =====================================
    build plan 9B                   field
    ==============================  =====================================
    dataset ID                      ``dataset_id``
    version ID                      ``version_id``
    dataset type                    ``dataset_kind``
    reporting/effective period      ``period``
    created timestamp               ``created_at``
    source filename                 ``source_filename``
    source byte size                ``source_byte_size``
    source content hash             ``source_sha256``
    row count                       ``row_count``
    column count                    ``column_count``
    column schema                   ``column_schema``
    parser information              ``parser_engine``, ``worksheet``
    minimum / maximum date          ``min_date``, ``max_date``
    report month                    ``period`` — see below
    replacement / supersession      ``supersedes``, ``supersession_reason``
    ==============================  =====================================

    **Report month and reporting period are one field on purpose.** For a
    monthly history version the reporting period *is* the report month; for a
    snapshot it is the month the snapshot is effective for. Recording the same
    month twice under two names would create two things that can disagree, and
    a version whose two months disagreed would be unreproducible in exactly the
    way build plan 9E exists to prevent.

    `dataset_kind` is denormalised onto the version deliberately, the same way
    :class:`~app.models.schemas.ActionReference` is copied into a Run manifest:
    a committed version is an audit record and has to stand on its own.

    **Immutability (build plan 9D).** Nothing rewrites a version once it is
    committed. A period is corrected by committing a *new* version that names
    the old one in `supersedes`, with `supersession_reason` explaining why. The
    reverse direction — "which version replaced this one" — is derived by the
    library from those forward pointers rather than written back into a record
    that is supposed to never change.
    """

    model_config = ConfigDict(frozen=True)

    schema_version: int = LIBRARY_SCHEMA_VERSION

    dataset_id: str
    version_id: str
    dataset_kind: DatasetKind

    period: str | None = Field(
        default=None,
        description=(
            "Reporting/effective period as YYYY-MM. Null only for a version "
            "that is not scoped to one month, such as a historical bootstrap "
            "covering several (build plan 10G)."
        ),
    )

    created_at: datetime

    source_filename: str = Field(
        description=(
            "The filename of the file this version was built from. Metadata "
            "only: it never becomes a path (build plan section 16)."
        )
    )
    source_byte_size: int
    source_sha256: str = Field(
        description="SHA-256 of the source file's bytes, as hex."
    )
    parser_engine: str | None = Field(
        default=None,
        description="Engine that read the source, recorded so a fallback is never silent.",
    )
    worksheet: str | None = Field(
        default=None, description="Worksheet read from an XLSX source; null for CSV."
    )

    row_count: int
    column_count: int
    column_schema: tuple[ColumnSchema, ...]

    min_date: date | None = Field(
        default=None, description="Earliest date found in the data, where it has one."
    )
    max_date: date | None = Field(
        default=None, description="Latest date found in the data, where it has one."
    )

    supersedes: str | None = Field(
        default=None,
        description="Version ID this version replaces (build plan 9D).",
    )
    supersession_reason: str | None = Field(
        default=None,
        description="Why the replaced version was replaced. Required alongside `supersedes`.",
    )

    @model_validator(mode="after")
    def _check_identity_and_supersession(self) -> DatasetVersion:
        with _as_validation_failure():
            parse_dataset_id(self.dataset_id)
            parse_version_id(self.version_id)
            if self.period is not None:
                parse_period(self.period)
            if self.supersedes is not None:
                parse_version_id(self.supersedes)

        if self.supersedes is not None:
            if self.supersedes == self.version_id:
                raise ValueError("A dataset version cannot supersede itself.")
            if not (self.supersession_reason or "").strip():
                raise ValueError(
                    "A version that supersedes another must record why "
                    "(build plan 9D)."
                )
        elif self.supersession_reason is not None:
            raise ValueError(
                "supersession_reason is only meaningful alongside supersedes."
            )

        if self.column_count != len(self.column_schema):
            raise ValueError(
                "column_count must match the number of columns described."
            )
        return self

    @property
    def columns(self) -> tuple[str, ...]:
        """This version's column names, in column order."""
        return tuple(column.name for column in self.column_schema)


@dataclass(frozen=True)
class DatasetCommit:
    """The request to commit one new version of a dataset (build plan 9B).

    A plain dataclass rather than a Pydantic model because it carries the
    DataFrame itself. What gets *persisted* is the validated
    :class:`DatasetVersion` the library derives from this.

    Provenance is required, not optional. A version whose source is unknown
    cannot be audited, cannot be recognised as an accidental re-upload
    (build plan 10C) and cannot explain a report it fed. :meth:`from_upload`
    derives the size and the hash from the bytes so a caller never has to.
    """

    #: The parsed source, exactly as it will be stored. This is the full
    #: snapshot: the library keeps no second copy of the raw upload.
    frame: pl.DataFrame

    #: The filename the file arrived under. Metadata only.
    source_filename: str
    source_byte_size: int
    source_sha256: str

    period: str | None = None
    parser_engine: str | None = None
    worksheet: str | None = None
    min_date: date | None = None
    max_date: date | None = None

    #: The version this one replaces, and why (build plan 9D). Both or neither.
    supersedes: str | None = None
    supersession_reason: str | None = None

    @classmethod
    def from_upload(
        cls,
        frame: pl.DataFrame,
        *,
        filename: str,
        payload: bytes,
        **fields: object,
    ) -> DatasetCommit:
        """Build a commit from the uploaded bytes the frame was parsed from.

        The byte size and content hash are measured here rather than passed in,
        so the two facts that identify a source file always agree with the file
        itself.
        """
        return cls(
            frame=frame,
            source_filename=filename,
            source_byte_size=len(payload),
            source_sha256=content_hash(payload),
            **fields,  # type: ignore[arg-type]
        )


