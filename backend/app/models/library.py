KNOWN_DATASETS: tuple[DatasetDefinition, ...] = (
    SALES_HISTORY,
    SAMPLE_HISTORY,
    ACCOUNT_ASSIGNMENTS,
)


def known_dataset(dataset_id: str) -> DatasetDefinition | None:
    """Return the declared definition for `dataset_id`, or None.

    Unknown IDs never fall back to a near match, exactly as the Action registry
    refuses to guess (build plan Phase 2.4).
    """
    for definition in KNOWN_DATASETS:
        if definition.id == dataset_id:
            return definition
    return None