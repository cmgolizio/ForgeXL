def _read_sheet(payload: bytes, worksheet: str) -> pl.DataFrame:
    """Read one worksheet of a multi-sheet workbook back into a dataframe.

    Uses the same engine the application parses uploads with, so a workbook
    this application could not itself ingest fails here.
    """
    reader = fastexcel.read_excel(payload)
    return reader.load_sheet(worksheet, header_row=0).to_polars()


def _sheet_names(payload: bytes) -> list[str]:
    """Worksheet names in workbook order, read out of the workbook part."""
    with zipfile.ZipFile(io.BytesIO(payload)) as archive:
        workbook = archive.read("xl/workbook.xml").decode("utf-8")
    return [
        html.unescape(name)
        for name in re.findall(r'<sheet name="([^"]*)"', workbook)
    ]