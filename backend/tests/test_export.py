def test_the_workbook_is_opened_in_memory() -> None:
    """xlsxwriter must be told not to use the OS temporary directory.

    Its default is to spool the workbook's parts through ``tempfile``. Build
    plan 6F.2 asks for an in-memory binary buffer, so the option is asserted
    directly as well as observed below.
    """
    assert export.WORKBOOK_OPTIONS["in_memory"] is True


def test_generating_a_workbook_creates_no_temporary_file(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Build plan 6F.2: nothing reaches a disk, including ``/tmp``."""
    created: list[str] = []
    real_mkstemp = tempfile.mkstemp
    real_named = tempfile.NamedTemporaryFile

    def spy_mkstemp(*args, **kwargs):
        handle, path = real_mkstemp(*args, **kwargs)
        created.append(path)
        return handle, path

    def spy_named(*args, **kwargs):
        opened = real_named(*args, **kwargs)
        created.append(getattr(opened, "name", "?"))
        return opened

    monkeypatch.setattr(tempfile, "mkstemp", spy_mkstemp)
    monkeypatch.setattr(tempfile, "NamedTemporaryFile", spy_named)

    export.to_xlsx_bytes(FRAME, worksheet="Result")
    export.to_workbook_bytes([("Kept", FRAME), ("Rejected", FRAME.head(1))])

    assert created == []


def test_a_cell_beginning_with_an_equals_sign_stays_text() -> None:
    """Build plan section 16: an uploaded value is never written as a formula."""
    frame = pl.DataFrame({"Note": ["=SUM(A1:A9)", "plain"]})

    payload = export.to_xlsx_bytes(frame, worksheet="Result")

    assert export.WORKBOOK_OPTIONS["strings_to_formulas"] is False
    assert parser.parse_tabular_bytes(payload, ".xlsx").frame[
        "Note"
    ].to_list() == ["=SUM(A1:A9)", "plain"]


# ---------------------------------------------------------------------------
# 6F.3 Sensible cell values
# ---------------------------------------------------------------------------


def test_numeric_columns_carry_no_display_format() -> None:
    """A small value must not be shown as 0.000, nor a large one regrouped.

    Polars applies ``#,##0.000`` to every numeric column by default. The stored
    value stays exact either way, but what Excel *shows* is what a reader
    trusts, so numbers are presented exactly as the data holds them
    (build plan 3.3 and 6F.3).
    """
    frame = pl.DataFrame({"Price": [0.000123, 1234.56789], "Qty": [3000, -4]})

    payload = export.to_xlsx_bytes(frame, worksheet="Result")

    with zipfile.ZipFile(io.BytesIO(payload)) as archive:
        styles = archive.read("xl/styles.xml").decode("utf-8")
    assert "#,##0" not in styles


def test_numeric_values_survive_the_workbook_exactly() -> None:
    frame = pl.DataFrame({"Price": [0.000123, 1234.56789]})

    payload = export.to_xlsx_bytes(frame, worksheet="Result")

    reloaded = parser.parse_tabular_bytes(payload, ".xlsx").frame
    assert reloaded["Price"].to_list() == [0.000123, 1234.56789]


def test_a_date_column_keeps_a_date_format() -> None:
    """Removing the numeric formats must not strip the date one too.

    An Excel date with no format renders as its serial number, which would be
    strictly less faithful than the formatted date.
    """
    frame = pl.DataFrame({"When": [date(2026, 1, 2), date(2026, 3, 4)]})

    payload = export.to_xlsx_bytes(frame, worksheet="Result")

    with zipfile.ZipFile(io.BytesIO(payload)) as archive:
        styles = archive.read("xl/styles.xml").decode("utf-8")
    assert "yyyy-mm-dd" in styles


