def test_the_service_retains_no_export_buffer() -> None:
    """Every call builds its bytes and lets them go; there is no cache to hold."""
    before = {
        name: value
        for name, value in vars(export).items()
        if isinstance(value, (dict, list, set)) and not name.isupper()
    }

    export.to_csv_bytes(FRAME)
    export.to_xlsx_bytes(FRAME, worksheet="Result")
    export.to_workbook_bytes([("Kept", FRAME), ("Rejected", FRAME)])

    after = {
        name: value
        for name, value in vars(export).items()
        if isinstance(value, (dict, list, set)) and not name.isupper()
    }
    assert before == after


def test_repeated_exports_of_one_frame_agree() -> None:
    """Generating on demand must be as deterministic as serving a stored file."""
    assert export.to_csv_bytes(FRAME) == export.to_csv_bytes(FRAME)

    first = parser.parse_tabular_bytes(
        export.to_xlsx_bytes(FRAME, worksheet="Result"), ".xlsx"
    ).frame
    second = parser.parse_tabular_bytes(
        export.to_xlsx_bytes(FRAME, worksheet="Result"), ".xlsx"
    ).frame
    assert first.equals(second)


