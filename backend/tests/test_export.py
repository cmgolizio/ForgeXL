STAMP = datetime(2026, 9, 1, 3, 45, 12, tzinfo=timezone.utc)


def test_the_filename_follows_the_forgexl_convention() -> None:
    assert (
        export.download_filename(
            action_id="product_master_builder",
            output_id="product_master",
            extension="xlsx",
            timestamp=STAMP,
        )
        == "forgexl-product-master-builder-product-master-20260901-034512.xlsx"
    )


def test_a_whole_run_workbook_omits_the_output() -> None:
    assert (
        export.download_filename(
            action_id="product_master_builder",
            extension="xlsx",
            timestamp=STAMP,
        )
        == "forgexl-product-master-builder-20260901-034512.xlsx"
    )


def test_the_same_run_and_output_always_produce_the_same_filename() -> None:
    """A re-download is the same file, so it arrives under the same name."""
    first = export.download_filename(
        action_id="a", output_id="b", extension="csv", timestamp=STAMP
    )
    second = export.download_filename(
        action_id="a", output_id="b", extension="csv", timestamp=STAMP
    )

    assert first == second


def test_the_timestamp_is_rendered_in_utc() -> None:
    """A machine in another timezone must not rename a Run it already recorded."""
    elsewhere = STAMP.astimezone(timezone(timedelta(hours=-7)))

    assert export.download_filename(
        action_id="a", extension="csv", timestamp=elsewhere
    ) == export.download_filename(
        action_id="a", extension="csv", timestamp=STAMP
    )


def test_a_naive_timestamp_is_read_as_utc() -> None:
    assert export.download_filename(
        action_id="a", extension="csv", timestamp=STAMP.replace(tzinfo=None)
    ) == export.download_filename(action_id="a", extension="csv", timestamp=STAMP)


@pytest.mark.parametrize(
    "action_id",
    ["../../escape", "a b/c", "Mixed_Case", "  ", "!!!", "x" * 200],
)
def test_a_filename_can_never_carry_anything_but_safe_characters(
    action_id: str,
) -> None:
    """Nothing in a name can escape a directory or break the header quoting."""
    filename = export.download_filename(
        action_id=action_id, output_id=action_id, extension="csv", timestamp=STAMP
    )

    assert re.fullmatch(r"[a-z0-9-]+\.csv", filename), filename
    assert "/" not in filename and "\\" not in filename
    assert ".." not in filename
    assert '"' not in filename


def test_two_outputs_of_one_run_get_different_filenames() -> None:
    """Downloading both into one folder must not overwrite the first."""
    kept = export.download_filename(
        action_id="split", output_id="kept", extension="csv", timestamp=STAMP
    )
    rejected = export.download_filename(
        action_id="split", output_id="rejected", extension="csv", timestamp=STAMP
    )

    assert kept != rejected


