# 6F.5 Worksheet names: understandable, valid, collision-safe
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    ("label", "expected"),
    [
        ("Product Master", "Product Master"),
        ("Deduplicated Data", "Deduplicated Data"),
        ("result", "result"),
        # Characters Excel refuses become spaces, and runs of space collapse.
        ("Kept / Rejected", "Kept Rejected"),
        ("A:B\\C/D?E*F[G]H", "A B C D E F G H"),
        # Excel refuses a leading or trailing apostrophe.
        ("'Quoted'", "Quoted"),
        # 31 characters is Excel's limit.
        ("a" * 40, "a" * 31),
        # Nothing usable left: a name is still required.
        ("", export.FALLBACK_WORKSHEET_NAME),
        ("[]", export.FALLBACK_WORKSHEET_NAME),
        ("'''", export.FALLBACK_WORKSHEET_NAME),
    ],
)
def test_a_label_becomes_a_name_excel_accepts(label: str, expected: str) -> None:
    name = export.worksheet_name(label)

    assert name == expected
    assert 1 <= len(name) <= export.MAX_WORKSHEET_NAME_LENGTH
    assert not (set(name) & export.INVALID_WORKSHEET_CHARACTERS)


def test_the_reserved_name_history_is_never_used() -> None:
    """Excel reserves "History"; a workbook using it will not open."""
    assert export.worksheet_name("History").casefold() != "history"
    assert export.worksheet_name("history").casefold() != "history"


def test_two_identical_labels_are_numbered_apart() -> None:
    assert export.worksheet_names(["Result", "Result", "Result"]) == (
        "Result",
        "Result 2",
        "Result 3",
    )


def test_labels_that_differ_only_in_case_are_numbered_apart() -> None:
    """Excel compares worksheet names case-insensitively, so this does too."""
    assert export.worksheet_names(["Result", "RESULT"]) == ("Result", "RESULT 2")


def test_labels_that_collide_only_after_truncation_are_numbered_apart() -> None:
    long_a = "Regional Sales Summary For The" + " North"
    long_b = "Regional Sales Summary For The" + " South"

    names = export.worksheet_names([long_a, long_b])

    assert names[0] != names[1]
    assert all(len(name) <= export.MAX_WORKSHEET_NAME_LENGTH for name in names)


def test_a_numbered_name_still_fits_excels_limit() -> None:
    names = export.worksheet_names(["b" * 40] * 3)

    assert len(set(names)) == 3
    assert all(len(name) <= export.MAX_WORKSHEET_NAME_LENGTH for name in names)


def test_colliding_labels_produce_a_workbook_excel_can_open() -> None:
    """The names are unique in the file itself, not merely in the helper."""
    payload = export.to_workbook_bytes(
        [("Result", FRAME), ("Result", FRAME), ("RESULT", FRAME)]
    )

    names = _sheet_names(payload)
    assert names == ["Result", "Result 2", "RESULT 3"]
    assert len({name.casefold() for name in names}) == 3


