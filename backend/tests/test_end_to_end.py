"""End-to-end spreadsheet regression tests (build plan 6H.3, 6H.4, 6H.6).

Build plan 6H.4 names the path these tests walk, and they walk all of it:

    create fixture in memory
            ↓
    submit upload
            ↓
    execute Action
            ↓
    retrieve preview
            ↓
    request export
            ↓
    read export
            ↓
    assert expected result

Every dataset is generated by `tests/fixtures/spreadsheets.py`, so no file
picker, no saved workbook and no company spreadsheet is involved (6H.1, 6H.8).
Every expected output comes from `tests/fixtures/action_cases.py`, where it is
stated in plain Python rather than produced by the code under test (6H.3).

Each case runs twice — once uploaded as CSV, once as XLSX — because a defect
in one reader is invisible to a suite that only exercises the other. Exports
are read back with ForgeXL's *own* parser, so an export the application could
not itself ingest fails here (6H.6).
"""

from __future__ import annotations

import fastexcel
import polars as pl
import pytest

from app.services import parser

from tests.fixtures import action_cases, spreadsheets as fx
from tests.fixtures.action_cases import ActionCase
from tests.helpers import normalise_rows, upload_file

CASE_IDS = action_cases.CASE_IDS


# ---------------------------------------------------------------------------
# Driving the real API
# ---------------------------------------------------------------------------


def run_case(client, case: ActionCase, extension: str) -> dict:
    """Submit `case`'s fixture in `extension` and return the run manifest.

    The fixture bytes are built here and handed straight to the request, which
    is what build plan 6H.4's first two steps mean by "create fixture in
    memory" then "submit upload": nothing is saved and reopened on the way.
    """
    response = client.post(
        "/api/runs",
        data={"action_id": case.action_id},
        files={
            case.slot_id: upload_file(
                case.source.filename(extension), case.source.payload(extension)
            )
        },
    )
    assert response.status_code == 200, response.text
    return response.json()


def preview_rows(client, run_id: str, output_id: str) -> list[list]:
    """Every row of an output, paged through the preview endpoint.

    Paged rather than fetched at once because the endpoint caps a page at 500
    rows; walking the pages is also what a client does, so this exercises the
    paging rather than avoiding it.
    """
    rows: list[list] = []
    offset = 0
    while True:
        response = client.get(
            f"/api/runs/{run_id}/outputs/{output_id}/preview",
            params={"offset": offset, "limit": 500},
        )
        assert response.status_code == 200, response.text
        page = response.json()
        rows.extend(page["rows"])
        offset += len(page["rows"])
        if offset >= page["total_rows"] or not page["rows"]:
            return rows


def download(client, run_id: str, output_id: str, export_format: str) -> bytes:
    response = client.get(
        f"/api/runs/{run_id}/outputs/{output_id}/download/{export_format}"
    )
    assert response.status_code == 200, response.text
    return response.content


def reread_export(payload: bytes, export_format: str) -> pl.DataFrame:
    """Read a downloaded export back with ForgeXL's own parser.

    Using the application's parser rather than a second reader is deliberate:
    an export ForgeXL could produce but not ingest would be a real defect, and
    this is what catches it (build plan 6H.6).
    """
    return parser.parse_tabular_bytes(payload, f".{export_format}").frame


def output_metadata(manifest: dict, output_id: str) -> dict:
    for output in manifest["outputs"]:
        if output["id"] == output_id:
            return output
    raise AssertionError(f"{output_id} not among {manifest['outputs']}")


