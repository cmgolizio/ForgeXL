@pytest.mark.parametrize("extension", fx.UPLOAD_EXTENSIONS)
def test_a_large_dataset_deduplicates_to_the_expected_result(
    client, extension: str
) -> None:
    """25,000 generated rows through the whole pipeline.

    Large enough that the answer could not be a coincidence of a handful of
    rows, and every value is still checked — the expected output is closed
    form because the generator repeats with a known period.
    """
    case = action_cases.large_deduplication_case()

    manifest = run_case(client, case, extension)
    output = output_metadata(manifest, case.output_id)

    assert output["input_row_count"] == action_cases.LARGE_ROW_COUNT
    assert output["row_count"] == fx.PRODUCT_POOL

    frame = reread_export(
        download(client, manifest["run_id"], case.output_id, "csv"), "csv"
    )
    assert normalise_rows(frame.rows()) == normalise_rows(case.expected.rows)


