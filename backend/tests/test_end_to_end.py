            producers = frame["Producer"].to_list()
            assert producers == [
                "Château Margaux",
                "Chateau Margaux",
                "Domaine Père et Fils",
                "Domaine Pere et Fils",
                "Bodegas Muñoz",
            ], f"{extension} -> {export_format}"


