def test_a_mixed_column_uploaded_as_csv_reaches_the_export_intact(client) -> None:
    """Every value of a mixed column survives upload, Action and export.

    The CSV path types the column as text, which loses nothing: `n/a` arrives
    in the downloaded file as `n/a`.
    """
    manifest = run_case(
        client,
        action_cases._deduplication_case(fx.MIXED_VALUES),
        fx.CSV_EXTENSION,
    )

    frame = reread_export(
        download(client, manifest["run_id"], "deduplicated_data", "csv"), "csv"
    )

    assert frame["Value"].to_list() == ["10", "n/a", "2.5", None, "-3", "0"]
