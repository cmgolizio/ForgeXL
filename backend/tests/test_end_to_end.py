@pytest.mark.parametrize("case", action_cases.CASES, ids=CASE_IDS)
@pytest.mark.parametrize("extension", fx.UPLOAD_EXTENSIONS)
def test_a_fixture_runs_to_the_expected_result(
    client, case: ActionCase, extension: str
) -> None:
    """Known input, known Action, known expected output (6H.3)."""
    manifest = run_case(client, case, extension)

    assert manifest["status"] == "succeeded"
    assert manifest["action"]["id"] == case.action_id

    output = output_metadata(manifest, case.output_id)
    assert output["columns"] == list(case.expected_columns)
    assert output["row_count"] == case.expected_row_count
    assert output["input_row_count"] == case.source.row_count


@pytest.mark.parametrize("case", action_cases.CASES, ids=CASE_IDS)
@pytest.mark.parametrize("extension", fx.UPLOAD_EXTENSIONS)
def test_the_preview_serves_the_expected_rows(
    client, case: ActionCase, extension: str
) -> None:
    """Step 4: retrieve preview, and check it against the expected output."""
    manifest = run_case(client, case, extension)

    rows = preview_rows(client, manifest["run_id"], case.output_id)

    assert normalise_rows(rows) == normalise_rows(case.expected.rows)


@pytest.mark.parametrize("case", action_cases.CASES, ids=CASE_IDS)
@pytest.mark.parametrize("extension", fx.UPLOAD_EXTENSIONS)
@pytest.mark.parametrize("export_format", ("csv", "xlsx"))
def test_the_export_reads_back_as_the_expected_result(
    client, case: ActionCase, extension: str, export_format: str
) -> None:
    """Steps 5-7: request the export, read it back, assert the result.

    The whole build plan 6H.4 pipeline closes here — the bytes a user would
    download are parsed again by the application and compared against the
    expected output the fixture states.
    """
    manifest = run_case(client, case, extension)

    frame = reread_export(
        download(client, manifest["run_id"], case.output_id, export_format),
        export_format,
    )

    assert tuple(frame.columns) == case.expected_columns
    assert normalise_rows(frame.rows()) == normalise_rows(case.expected.rows)


@pytest.mark.parametrize("case", action_cases.CASES, ids=CASE_IDS)
def test_a_csv_upload_and_an_xlsx_upload_reach_the_same_result(
    client, case: ActionCase
) -> None:
    """One fixture, two upload paths, one answer.

    A reader that quietly disagreed with the other would show up here rather
    than in whichever format a developer happened to test by hand.
    """
    from_csv = run_case(client, case, fx.CSV_EXTENSION)
    from_xlsx = run_case(client, case, fx.XLSX_EXTENSION)

    assert from_csv["metrics"] == from_xlsx["metrics"]
    assert from_csv["audit"]["rows_affected"] == from_xlsx["audit"]["rows_affected"]

    csv_rows = preview_rows(client, from_csv["run_id"], case.output_id)
    xlsx_rows = preview_rows(client, from_xlsx["run_id"], case.output_id)
    assert normalise_rows(csv_rows) == normalise_rows(xlsx_rows)


