"""The Data Library's domain model (build plan 9B).

These tests are about the *records*, independent of where they are stored:
what a dataset version must record, what a version ID may be, what a reporting
period may be, and the rules a supersession has to satisfy before anything is
written.

The storage half is in `test_data_library.py`; the durability half is in
`test_library_persistence.py`.
"""

from __future__ import annotations

import json
from datetime import date, datetime, timezone

import polars as pl
import pytest
from pydantic import ValidationError

from app.errors import (
    InvalidDatasetCommitError,
    UnknownDatasetError,
    UnknownDatasetVersionError,
)
from app.models.library import (
    ACCOUNT_ASSIGNMENTS,
    KNOWN_DATASETS,
    LIBRARY_SCHEMA_VERSION,
    SALES_HISTORY,
    SAMPLE_HISTORY,
    Dataset,
    DatasetCommit,
    DatasetDefinition,
    DatasetKind,
    DatasetVersion,
    content_hash,
    known_dataset,
    new_version_id,
    parse_dataset_id,
    parse_period,
    parse_version_id,
)
from app.models.schemas import ColumnKind, ColumnSchema


def _version(**overrides) -> DatasetVersion:
    """A complete, valid version record; override one field per test."""
    fields = {
        "dataset_id": "sales_history",
        "version_id": new_version_id(),
        "dataset_kind": DatasetKind.HISTORY,
        "period": "2026-09",
        "created_at": datetime(2026, 9, 30, 12, 0, tzinfo=timezone.utc),
        "source_filename": "September Sales.csv",
        "source_byte_size": 4096,
        "source_sha256": content_hash(b"September Sales"),
        "parser_engine": "polars-csv",
        "row_count": 3,
        "column_count": 2,
        "column_schema": (
            ColumnSchema(name="Account", dtype="String", kind=ColumnKind.TEXT),
            ColumnSchema(name="Amount", dtype="Float64", kind=ColumnKind.NUMBER),
        ),
    }
    fields.update(overrides)
    return DatasetVersion(**fields)


