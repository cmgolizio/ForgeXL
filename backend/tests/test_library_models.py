def test_a_version_records_everything_build_plan_9b_lists() -> None:
    """Each item on 9B's list, present and populated."""
    version = _version(
        min_date=date(2026, 9, 1),
        max_date=date(2026, 9, 30),
        worksheet="Sheet1",
    )

    assert version.dataset_id == "sales_history"
    assert parse_version_id(version.version_id) == version.version_id
    assert version.dataset_kind is DatasetKind.HISTORY
    assert version.period == "2026-09"
    assert version.created_at.tzinfo is not None
    assert version.source_filename == "September Sales.csv"
    assert version.source_byte_size == 4096
    assert version.source_sha256 == content_hash(b"September Sales")
    assert version.row_count == 3
    assert version.column_count == 2
    assert version.columns == ("Account", "Amount")
    assert version.parser_engine == "polars-csv"
    assert version.worksheet == "Sheet1"
    assert version.min_date == date(2026, 9, 1)
    assert version.max_date == date(2026, 9, 30)
    assert version.supersedes is None


def test_a_version_record_is_frozen() -> None:
    """A committed version is immutable in memory as well as on disk (9D)."""
    version = _version()

    with pytest.raises(ValidationError):
        version.period = "2026-10"  # type: ignore[misc]


def test_a_version_may_cover_no_single_period() -> None:
    """Build plan 10G's historical bootstrap spans several months."""
    version = _version(period=None)

    assert version.period is None


def test_a_version_column_count_must_match_its_schema() -> None:
    """The two describe the same table; a record where they disagree is wrong."""
    with pytest.raises(ValidationError):
        _version(column_count=5)


def test_a_version_id_that_is_not_a_uuid_cannot_be_recorded() -> None:
    with pytest.raises(ValidationError):
        _version(version_id="september")


def test_a_version_period_that_is_not_a_month_cannot_be_recorded() -> None:
    with pytest.raises(ValidationError):
        _version(period="September")


