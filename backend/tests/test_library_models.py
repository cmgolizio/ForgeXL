@pytest.mark.parametrize(
    "dataset_id", ["sales_history", "s", "a1", "account_assignments"]
)
def test_a_well_formed_dataset_id_is_accepted(dataset_id: str) -> None:
    assert parse_dataset_id(dataset_id) == dataset_id


@pytest.mark.parametrize(
    "dataset_id",
    [
        "../sales_history",
        "sales history",
        "sales-history",
        "/etc/passwd",
        "Sales_History",
        "1sales",
        "",
        "sales_history/versions",
        "..",
        ".",
    ],
)
def test_an_unsafe_dataset_id_is_refused_for_its_shape(dataset_id: str) -> None:
    """Refused before the library is asked whether it holds one.

    A dataset ID is the one value that becomes a directory name, so its shape
    is checked rather than trusted.
    """
    with pytest.raises(UnknownDatasetError):
        parse_dataset_id(dataset_id)


def test_a_generated_version_id_is_a_uuid() -> None:
    """Build plan 9B: generated by ForgeXL, never from a user filename."""
    generated = new_version_id()

    assert parse_version_id(generated) == generated


def test_two_generated_version_ids_differ() -> None:
    assert new_version_id() != new_version_id()


@pytest.mark.parametrize(
    "version_id",
    [
        "../../etc/passwd",
        "September Sales.csv",
        "not-a-uuid",
        "",
        "6e444a2b371b47d5b9d589b0fbd249c9",  # no hyphens is not the canonical form
    ],
)
def test_a_version_id_that_is_not_a_uuid_is_refused(version_id: str) -> None:
    with pytest.raises(UnknownDatasetVersionError):
        parse_version_id(version_id)


def test_a_version_id_is_canonicalised_to_lowercase() -> None:
    """The same rule Run IDs follow, so a version is found however it is typed.

    Canonicalising rather than refusing is safe here because the canonical form
    is what becomes the directory name, and it is a UUID either way.
    """
    canonical = "6e444a2b-371b-47d5-b9d5-89b0fbd249c9"

    assert parse_version_id(canonical.upper()) == canonical


def test_the_content_hash_is_sha256_of_the_source_bytes() -> None:
    """One definition, so build plan 10C can compare two imports meaningfully."""
    import hashlib

    payload = b"SKU,Volume\nA-1,750ml\n"

    assert content_hash(payload) == hashlib.sha256(payload).hexdigest()


def test_identical_sources_hash_alike_and_different_ones_do_not() -> None:
    assert content_hash(b"same") == content_hash(b"same")
    assert content_hash(b"same") != content_hash(b"same ")


