def test_account_assignments_is_a_snapshot_and_the_histories_are_not() -> None:
    """Build plan 9E: ownership is stored per effective period, not as one file."""
    assert ACCOUNT_ASSIGNMENTS.kind is DatasetKind.SNAPSHOT
    assert SALES_HISTORY.kind is DatasetKind.HISTORY
    assert SAMPLE_HISTORY.kind is DatasetKind.HISTORY


def test_sales_and_samples_are_separate_logical_datasets() -> None:
    """Build plan 10D forbids folding one into the other; they start apart."""
    assert SALES_HISTORY.id != SAMPLE_HISTORY.id


def test_a_declared_dataset_is_found_by_its_stable_id() -> None:
    assert known_dataset("sales_history") is SALES_HISTORY


