def test_a_commit_measures_its_source_from_the_uploaded_bytes() -> None:
    """So the two facts that identify a source file always agree with it."""
    payload = b"Account,Amount\nAcme,10\n"
    frame = pl.DataFrame({"Account": ["Acme"], "Amount": [10]})

    commit = DatasetCommit.from_upload(
        frame, filename="September Sales.csv", payload=payload, period="2026-09"
    )

    assert commit.source_filename == "September Sales.csv"
    assert commit.source_byte_size == len(payload)
    assert commit.source_sha256 == content_hash(payload)
    assert commit.period == "2026-09"


def test_a_commit_defaults_to_no_period_and_no_supersession() -> None:
    commit = DatasetCommit(
        frame=pl.DataFrame({"Account": ["Acme"]}),
        source_filename="bootstrap.csv",
        source_byte_size=1,
        source_sha256=content_hash(b"x"),
    )

    assert commit.period is None
    assert commit.supersedes is None
    assert commit.supersession_reason is None