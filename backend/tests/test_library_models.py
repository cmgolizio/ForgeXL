def test_periods_sort_chronologically_as_text() -> None:
    """Why YYYY-MM is the stored form: ordering needs no parsing."""
    months = ["2026-10", "2025-12", "2026-01", "2026-09"]

    assert sorted(months) == ["2025-12", "2026-01", "2026-09", "2026-10"]


