def test_a_replacement_records_what_it_replaces_and_why() -> None:
    replaced = new_version_id()

    version = _version(
        supersedes=replaced,
        supersession_reason="The September export was taken before month end.",
    )

    assert version.supersedes == replaced
    assert "month end" in (version.supersession_reason or "")


def test_a_replacement_without_a_reason_is_refused() -> None:
    """Build plan 9D: retain enough metadata to explain the change."""
    with pytest.raises(ValidationError):
        _version(supersedes=new_version_id())


def test_a_blank_reason_does_not_count_as_a_reason() -> None:
    with pytest.raises(ValidationError):
        _version(supersedes=new_version_id(), supersession_reason="   ")


def test_a_reason_without_a_replacement_is_refused() -> None:
    """It would explain a change the record does not claim to have made."""
    with pytest.raises(ValidationError):
        _version(supersession_reason="Corrected.")


def test_a_version_cannot_supersede_itself() -> None:
    version_id = new_version_id()

    with pytest.raises(ValidationError):
        _version(
            version_id=version_id,
            supersedes=version_id,
            supersession_reason="Nonsense.",
        )


