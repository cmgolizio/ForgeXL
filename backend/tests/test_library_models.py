def test_a_version_record_round_trips_through_json() -> None:
    """The exact operation the library performs against the filesystem."""
    version = _version(
        min_date=date(2026, 9, 1),
        max_date=date(2026, 9, 30),
        supersedes=new_version_id(),
        supersession_reason="Restated.",
    )

    restored = DatasetVersion.model_validate_json(version.model_dump_json())

    assert restored == version


def test_a_dataset_record_round_trips_through_json() -> None:
    dataset = Dataset.of(SALES_HISTORY)

    restored = Dataset.model_validate_json(dataset.model_dump_json())

    assert restored == dataset
    assert restored.definition() == SALES_HISTORY


def test_a_record_carries_its_format_version() -> None:
    """So a record written by an older build stays identifiable."""
    payload = json.loads(_version().model_dump_json())

    assert payload["schema_version"] == LIBRARY_SCHEMA_VERSION


def test_a_stored_record_contains_no_filesystem_path() -> None:
    """Build plan 9C: physical locations are not part of the record."""
    payload = _version().model_dump_json()

    for fragment in ("/home/", "/Users/", "/tmp", "data/library", ".parquet"):
        assert fragment not in payload


